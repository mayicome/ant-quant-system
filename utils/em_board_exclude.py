def is_excluded_em_board(name: str) -> bool:
    """是否应从东财热门合格榜 / 股票信息标签中排除。"""
    n = str(name or "").strip()
    if not n or n == "nan":
        return True
    if n in EXCLUDED_BOARD_EXACT:
        return True
    # ST 开头（如 ST板块 少见；ST股已在 exact）
    if n.upper().startswith("ST") and ("股" in n or n.upper() == "ST"):
        return True
    return any(k in n for k in EXCLUDED_BOARD_KEYWORDS)
